func TestEmitGeneratedHeader(t *testing.T) {
	cfg := EmitConfig{
		PackageName:  "font",
		FontID:       "spleen-5x8",
		StructName:   "spleen5x8Face",
		ConstName:    "Spleen5x8ID",
		ArrayName:    "spleen5x8Rows",
		GlyphWidth:   5,
		GlyphHeight:  8,
		GlyphAdvance: 6,
		RowHeight:    10,
		GlyphMap:     map[rune][]uint32{32: {0, 0, 0, 0, 0, 0, 0, 0}},
	}

	var buf bytes.Buffer
	if err := Emit(&buf, cfg); err != nil {
		t.Fatalf("Emit failed: %v", err)
	}

	output := buf.String()

	// The first line must be the generated comment.
	if !strings.HasPrefix(output, "// Code generated by tools/fontgen; DO NOT EDIT.\n") {
		t.Errorf("output does not start with generated comment:\n%s", output[:min(len(output), 100)])
	}
}

