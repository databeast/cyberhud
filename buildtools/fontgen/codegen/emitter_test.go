func TestEmitMethods(t *testing.T) {
	cfg := EmitConfig{
		PackageName:  "font",
		FontID:       "spleen-6x12",
		StructName:   "spleen6x12Face",
		ConstName:    "Spleen6x12ID",
		ArrayName:    "spleen6x12Rows",
		GlyphWidth:   6,
		GlyphHeight:  12,
		GlyphAdvance: 7,
		RowHeight:    14,
		GlyphMap:     map[rune][]uint32{32: make([]uint32, 12), '?': make([]uint32, 12)},
	}

	var buf bytes.Buffer
	if err := Emit(&buf, cfg); err != nil {
		t.Fatalf("Emit failed: %v", err)
	}

	output := buf.String()

	// ID method
	if !strings.Contains(output, "func (spleen6x12Face) ID() string { return Spleen6x12ID }") {
		t.Error("missing or incorrect ID() method")
	}

	// Metrics method
	if !strings.Contains(output, "return Metrics{GlyphWidth: 6, GlyphHeight: 12, GlyphAdvance: 7, RowHeight: 14}") {
		t.Error("missing or incorrect Metrics() return")
	}

	// GlyphRow bounds check
	if !strings.Contains(output, "if row < 0 || row >= 12 {") {
		t.Error("missing or incorrect row bounds check in GlyphRow()")
	}

	// Map lookup
	if !strings.Contains(output, "if data, ok := spleen6x12RowsMap[ch]; ok {") {
		t.Error("missing map lookup in GlyphRow()")
	}

	// Fallback lookup
	if !strings.Contains(output, "if data, ok := spleen6x12RowsMap[spleen6x12RowsFallback]; ok {") {
		t.Error("missing fallback lookup in GlyphRow()")
	}
}

