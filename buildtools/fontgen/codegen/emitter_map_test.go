func TestEmitMapBasedMethods(t *testing.T) {
	cfg := EmitConfig{
		PackageName:  "font",
		FontID:       "matrix-code",
		StructName:   "matrixcodeFace",
		ConstName:    "MatrixCodeID",
		ArrayName:    "matrixcodeRows",
		GlyphWidth:   7,
		GlyphHeight:  12,
		GlyphAdvance: 8,
		RowHeight:    14,
		GlyphMap: map[rune][]uint32{
			'A': {0x10, 0x28, 0x44, 0x82, 0xFE, 0x82, 0x82, 0x82, 0x00, 0x00, 0x00, 0x00},
		},
		FallbackChar: '?',
	}

	var buf bytes.Buffer
	if err := Emit(&buf, cfg); err != nil {
		t.Fatalf("Emit failed: %v", err)
	}

	output := buf.String()

	// ID method.
	if !strings.Contains(output, "func (matrixcodeFace) ID() string { return MatrixCodeID }") {
		t.Error("missing or incorrect ID() method")
	}

	// Metrics method.
	if !strings.Contains(output, "return Metrics{GlyphWidth: 7, GlyphHeight: 12, GlyphAdvance: 8, RowHeight: 14}") {
		t.Error("missing or incorrect Metrics() return")
	}

	// GlyphRow row bounds check.
	if !strings.Contains(output, "if row < 0 || row >= 12 {") {
		t.Error("missing row bounds check in GlyphRow()")
	}

	// Map lookup.
	if !strings.Contains(output, "if data, ok := matrixcodeRowsMap[ch]; ok {") {
		t.Error("missing map lookup in GlyphRow()")
	}

	// Fallback lookup.
	if !strings.Contains(output, "if data, ok := matrixcodeRowsMap[matrixcodeRowsFallback]; ok {") {
		t.Error("missing fallback lookup in GlyphRow()")
	}

	// Final return 0.
	if !strings.Contains(output, "\treturn 0\n}") {
		t.Error("missing final return 0 in GlyphRow()")
	}
}

