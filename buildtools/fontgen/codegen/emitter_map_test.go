func TestEmitMapBasedHeader(t *testing.T) {
	cfg := EmitConfig{
		PackageName:  "font",
		FontID:       "matrix-code",
		StructName:   "matrixcodeFace",
		ConstName:    "MatrixCodeID",
		ArrayName:    "matrixcodeRows",
		GlyphWidth:   7,
		GlyphHeight:  12,
		GlyphAdvance: 8,
		RowHeight:    14,
		GlyphMap: map[rune][]uint32{
			'A': {0x10, 0x28, 0x44, 0x82, 0xFE, 0x82, 0x82, 0x82, 0x00, 0x00, 0x00, 0x00},
			'B': {0xFC, 0x82, 0x82, 0xFC, 0x82, 0x82, 0x82, 0xFC, 0x00, 0x00, 0x00, 0x00},
		},
		FallbackChar: '?',
	}

	var buf bytes.Buffer
	if err := Emit(&buf, cfg); err != nil {
		t.Fatalf("Emit failed: %v", err)
	}

	output := buf.String()

	if !strings.HasPrefix(output, "// Code generated by tools/fontgen; DO NOT EDIT.\n") {
		t.Errorf("output does not start with generated comment")
	}
	if !strings.Contains(output, "package font\n") {
		t.Errorf("output missing package declaration")
	}
}

