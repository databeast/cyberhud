func TestEmitMapBasedIdempotent(t *testing.T) {
	cfg := EmitConfig{
		PackageName:  "font",
		FontID:       "test-idem",
		StructName:   "testidemFace",
		ConstName:    "TestIdemID",
		ArrayName:    "testidemRows",
		GlyphWidth:   4,
		GlyphHeight:  3,
		GlyphAdvance: 5,
		RowHeight:    4,
		GlyphMap: map[rune][]uint32{
			'A':    {0x01, 0x02, 0x03},
			'Z':    {0x04, 0x05, 0x06},
			0xFF66: {0x07, 0x08, 0x09}, // Katakana half-width
		},
		FallbackChar: '?',
	}

	var buf1, buf2 bytes.Buffer
	if err := Emit(&buf1, cfg); err != nil {
		t.Fatalf("first Emit failed: %v", err)
	}
	if err := Emit(&buf2, cfg); err != nil {
		t.Fatalf("second Emit failed: %v", err)
	}

	if buf1.String() != buf2.String() {
		t.Error("two Emit calls produced different output (not idempotent)")
	}
}

func TestEmitMapBasedNoLegacyArrayGenerated(t *testing.T) {
	// When using GlyphMap path, the legacy [95][N]uint32 array should NOT appear.
	cfg := EmitConfig{
		PackageName:  "font",
		FontID:       "test-noarr",
		StructName:   "testnoarrFace",
		ConstName:    "TestNoarrID",
		ArrayName:    "testnoarrRows",
		GlyphWidth:   4,
		GlyphHeight:  2,
		GlyphAdvance: 5,
		RowHeight:    3,
		GlyphMap: map[rune][]uint32{
			'A': {0x01, 0x02},
		},
	}

	var buf bytes.Buffer
	if err := Emit(&buf, cfg); err != nil {
		t.Fatalf("Emit failed: %v", err)
	}

	output := buf.String()
	if strings.Contains(output, "[95][") {
		t.Errorf("map-based emit path should not generate legacy [95] array.\nGot:\n%s", output)
	}
	if strings.Contains(output, "ch - 32") {
		t.Errorf("map-based emit path should not use 'ch - 32' indexing.\nGot:\n%s", output)
	}
}

