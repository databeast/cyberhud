func TestEmitMapBasedSortedRunes(t *testing.T) {
	// Ensure that runes in the map are emitted in sorted order for determinism.
	cfg := EmitConfig{
		PackageName:  "font",
		FontID:       "test-sort",
		StructName:   "testsortFace",
		ConstName:    "TestSortID",
		ArrayName:    "testsortRows",
		GlyphWidth:   4,
		GlyphHeight:  2,
		GlyphAdvance: 5,
		RowHeight:    3,
		GlyphMap: map[rune][]uint32{
			'Z': {0x01, 0x02},
			'A': {0x03, 0x04},
			'M': {0x05, 0x06},
		},
	}

	var buf bytes.Buffer
	if err := Emit(&buf, cfg); err != nil {
		t.Fatalf("Emit failed: %v", err)
	}

	output := buf.String()

	// A=65, M=77, Z=90. They should appear in this order.
	posA := strings.Index(output, "65: {")
	posM := strings.Index(output, "77: {")
	posZ := strings.Index(output, "90: {")

	if posA < 0 || posM < 0 || posZ < 0 {
		t.Fatalf("not all rune entries found in output")
	}
	if !(posA < posM && posM < posZ) {
		t.Errorf("runes not emitted in sorted order: A@%d, M@%d, Z@%d", posA, posM, posZ)
	}
}

